-- Permanently seal catalog releases when they stop being active.  A release
-- may only be assembled before its first activation; it must never acquire
-- more graph rows after it has been deactivated.
CREATE TABLE gateway.catalog_release_seal (
    organization_id UUID NOT NULL,
    release_id UUID NOT NULL,
    sealed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (organization_id, release_id),
    CONSTRAINT catalog_release_seal_release_fk
        FOREIGN KEY (organization_id, release_id)
        REFERENCES gateway.catalog_release (organization_id, id)
        ON DELETE CASCADE
);

-- Permit normal organization cleanup to remove the active pointer together
-- with its release. Direct catalog release mutation remains blocked by the
-- existing immutable trigger.
ALTER TABLE gateway.catalog_active_release
    DROP CONSTRAINT catalog_active_release_fk,
    ADD CONSTRAINT catalog_active_release_fk FOREIGN KEY (organization_id, release_id)
        REFERENCES gateway.catalog_release (organization_id, id) ON DELETE CASCADE;

CREATE OR REPLACE FUNCTION gateway.prevent_catalog_seal_mutation()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    -- Permit only referential-action cleanup (for example, organization
    -- deletion). Direct attempts to remove or alter a seal remain forbidden.
    IF TG_OP = 'DELETE' AND pg_trigger_depth() > 1 THEN
        RETURN OLD;
    END IF;
    RAISE EXCEPTION 'catalog release seals are immutable';
END;
$$;

CREATE TRIGGER catalog_release_seal_immutable
BEFORE UPDATE OR DELETE ON gateway.catalog_release_seal
FOR EACH ROW EXECUTE FUNCTION gateway.prevent_catalog_seal_mutation();

CREATE OR REPLACE FUNCTION gateway.prevent_catalog_active_insert()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM gateway.catalog_release_seal s
        WHERE s.organization_id = NEW.organization_id
          AND s.release_id = NEW.release_id
    ) THEN
        RAISE EXCEPTION 'catalog release is permanently sealed';
    END IF;
    IF EXISTS (
        SELECT 1
        FROM gateway.catalog_active_release a
        WHERE a.organization_id = NEW.organization_id
          AND a.release_id = NEW.release_id
    ) THEN
        RAISE EXCEPTION 'active catalog release rows are immutable';
    END IF;
    RETURN NEW;
END;
$$;

-- Catalog graph rows are immutable during their lifetime, but their existing
-- organization/release ON DELETE CASCADE lifecycle must remain usable. A
-- nested delete is generated by PostgreSQL's referential-action trigger, not
-- by a caller mutating the graph directly.
CREATE OR REPLACE FUNCTION gateway.prevent_catalog_mutation()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'DELETE' AND pg_trigger_depth() > 1 THEN
        RETURN OLD;
    END IF;
    RAISE EXCEPTION 'active catalog release rows are immutable';
END;
$$;

CREATE OR REPLACE FUNCTION gateway.seal_catalog_release_on_deactivate()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    -- Organization deletion may cascade the release before its active-pointer
    -- row. There is nothing durable to seal once the release itself is gone.
    IF NOT EXISTS (
        SELECT 1
        FROM gateway.catalog_release r
        WHERE r.organization_id = OLD.organization_id
          AND r.id = OLD.release_id
    ) THEN
        RETURN NEW;
    END IF;
    IF TG_OP = 'UPDATE'
       AND OLD.release_id IS NOT DISTINCT FROM NEW.release_id THEN
        RETURN NEW;
    END IF;
    INSERT INTO gateway.catalog_release_seal (organization_id, release_id)
    VALUES (OLD.organization_id, OLD.release_id)
    ON CONFLICT (organization_id, release_id) DO NOTHING;
    RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION gateway.prevent_catalog_sealed_activation()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM gateway.catalog_release_seal s
        WHERE s.organization_id = NEW.organization_id
          AND s.release_id = NEW.release_id
    ) THEN
        RAISE EXCEPTION 'catalog release is permanently sealed';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER catalog_active_release_seal_update
BEFORE UPDATE ON gateway.catalog_active_release
FOR EACH ROW EXECUTE FUNCTION gateway.seal_catalog_release_on_deactivate();

CREATE TRIGGER catalog_active_release_seal_delete
BEFORE DELETE ON gateway.catalog_active_release
FOR EACH ROW EXECUTE FUNCTION gateway.seal_catalog_release_on_deactivate();

CREATE TRIGGER catalog_active_release_sealed_activation
BEFORE INSERT OR UPDATE ON gateway.catalog_active_release
FOR EACH ROW EXECUTE FUNCTION gateway.prevent_catalog_sealed_activation();

-- Replace the generic provenance trigger with shape-specific validation.  The
-- accounting reservation copies the complete price snapshot and deployment
-- identity; the inference trace copies complete catalog provenance plus its
-- model and price identity.
DROP TRIGGER accounting_reservation_catalog_provenance_validate
    ON gateway.accounting_reservation;
DROP TRIGGER inference_trace_catalog_provenance_validate
    ON gateway.inference_trace;

CREATE OR REPLACE FUNCTION gateway.validate_accounting_reservation_catalog_provenance()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    expected_digest BYTEA;
    expected_deployment_id UUID;
    expected_price_id UUID;
    expected_deployment TEXT;
    expected_model TEXT;
    expected_operation TEXT;
    expected_family TEXT;
    expected_source TEXT;
    expected_source_version TEXT;
    expected_confidence TEXT;
    expected_currency CHAR(3);
    expected_input BIGINT;
    expected_output BIGINT;
    expected_cached_input BIGINT;
    expected_reasoning BIGINT;
    expected_other BIGINT;
BEGIN
    IF NEW.catalog_release_id IS NULL THEN
        RETURN NEW;
    END IF;

    SELECT cr.digest, r.deployment_id, r.price_id, d.name, d.model,
           r.operation, p.family, pr.source, pr.source_version,
           pr.confidence, pr.currency, pr.input_minor_per_token,
           pr.output_minor_per_token, pr.cached_input_minor_per_token,
           pr.reasoning_minor_per_token, pr.other_minor_per_token
      INTO expected_digest, expected_deployment_id, expected_price_id,
           expected_deployment, expected_model, expected_operation,
           expected_family, expected_source, expected_source_version,
           expected_confidence, expected_currency, expected_input,
           expected_output, expected_cached_input, expected_reasoning,
           expected_other
      FROM gateway.catalog_route r
      JOIN gateway.catalog_release cr
        ON cr.organization_id = r.organization_id
       AND cr.id = r.release_id
      JOIN gateway.catalog_deployment d
        ON d.organization_id = r.organization_id
       AND d.release_id = r.release_id
       AND d.id = r.deployment_id
      JOIN gateway.catalog_provider_account p
        ON p.organization_id = d.organization_id
       AND p.release_id = d.release_id
       AND p.id = d.provider_account_id
       AND p.adapter_instance_key = d.adapter_instance_key
      JOIN gateway.catalog_price pr
        ON pr.organization_id = r.organization_id
       AND pr.release_id = r.release_id
       AND pr.id = r.price_id
      WHERE r.organization_id = NEW.organization_id
        AND r.release_id = NEW.catalog_release_id
        AND r.id = NEW.catalog_route_id;

    IF expected_digest IS NULL
       OR expected_digest IS DISTINCT FROM NEW.catalog_digest
       OR expected_deployment_id IS DISTINCT FROM NEW.catalog_deployment_id
       OR expected_price_id IS DISTINCT FROM NEW.catalog_price_id
       OR expected_deployment IS DISTINCT FROM NEW.deployment
       OR expected_model IS DISTINCT FROM NEW.model
       OR expected_operation IS DISTINCT FROM NEW.catalog_operation
       OR expected_family IS DISTINCT FROM NEW.catalog_family
       OR expected_source IS DISTINCT FROM NEW.catalog_price_source
       OR expected_source_version IS DISTINCT FROM NEW.price_version
       OR expected_confidence IS DISTINCT FROM NEW.pricing_confidence
       OR expected_currency IS DISTINCT FROM NEW.currency
       OR expected_input IS DISTINCT FROM NEW.input_price_minor
       OR expected_output IS DISTINCT FROM NEW.output_price_minor
       OR expected_cached_input IS DISTINCT FROM NEW.cached_input_price_minor
       OR expected_reasoning IS DISTINCT FROM NEW.reasoning_price_minor
       OR expected_other IS DISTINCT FROM NEW.other_price_minor
    THEN
        RAISE EXCEPTION 'catalog reservation provenance does not match catalog rows';
    END IF;
    RETURN NEW;
END;
$$;

