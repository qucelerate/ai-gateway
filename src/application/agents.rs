// Agent admin application service: list an organization's agents, create
// and disable them, and create and revoke their tokens.
//
// Agents are members, so reads need `members_list` and writes
// `member_mutate`, organization-wide. A caller acts only on agents at or
// below their own rank, as for invitations: an admin can neither create an
// owner agent nor mint a token for one. Writes run through the admin
// mutation coordinator, so each is idempotent and audited (`agent.created`,
// `agent.disabled`, `agent_token.created`, `agent_token.revoked`) in the
// same transaction as the change.
//
// A token is generated by the store and returned once, in the response that
// created it; it is never logged, audited or persisted, so a replay reports
// `token: null` with `replay: true`.

use serde::Serialize;
use uuid::Uuid;

use crate::application::{
    admin_identities::{MutationOutcome, deterministic_target_id},
    invitations::{grantable_roles, may_invite},
};
use crate::domain::{
    admin::{
        AdminIdempotencyKey, AdminOperation, AdminPermission, AdminScope, IdempotencyResultMetadata,
    },
    agents::{AgentInput, AgentTokenInput, AgentView, CreatedAgentToken, valid_text},
    audit::{AuditAction, AuditSnapshot, AuditTargetResource},
    identity::{MembershipRole, OrganizationId, UserAccountId},
    version::IfMatch,
};
use crate::persistence::{
    admin::{AdminMutationRequest, AdminStore, AdminStoreError, MutationStart},
    agents::{AgentStore, AgentStoreError},
    invitations::InvitationStore,
};

pub const ROUTE_AGENTS: &str = "/api/admin/v1/organizations/{org}/agents";
pub const ROUTE_AGENT: &str = "/api/admin/v1/organizations/{org}/agents/{agent_id}";
pub const ROUTE_AGENT_TOKENS: &str = "/api/admin/v1/organizations/{org}/agents/{agent_id}/tokens";
pub const ROUTE_AGENT_TOKEN: &str =
    "/api/admin/v1/organizations/{org}/agents/{agent_id}/tokens/{token_id}";

#[derive(Debug)]
pub enum AgentError {
    Forbidden,
    /// The agent's role is above the caller's own.
    EscalationDenied,
    NotFound,
    Invalid(&'static str),
    NameTaken,
    TooManyAgents,
    TooManyTokens,
    /// The agent is disabled, so it gets no new token.
    AgentDisabled,
    /// Disabling the agent would leave the organization without an owner.
    LastOwner,
    IdempotencyConflict,
    IdempotencyInProgress,
    Store(String),
    Admin(AdminStoreError),
}

impl From<sqlx::Error> for AgentError {
    fn from(error: sqlx::Error) -> Self {
        Self::Store(format!("{error:?}"))
    }
}

impl From<AgentStoreError> for AgentError {
    fn from(error: AgentStoreError) -> Self {
        match error {
            AgentStoreError::NameTaken => Self::NameTaken,
            AgentStoreError::TooManyAgents => Self::TooManyAgents,
            AgentStoreError::TooManyTokens => Self::TooManyTokens,
            AgentStoreError::AgentUnavailable => Self::AgentDisabled,
            AgentStoreError::UnknownServiceAccount => {
                Self::Invalid("service_account_id is not a service account of the organization")
            }
            AgentStoreError::LastOwner => Self::LastOwner,
            AgentStoreError::Audit(error) => Self::Admin(error),
            other => Self::Store(format!("{other:?}")),
        }
    }
}

/// The organization's agents, with the roles the caller may give one (none
/// without `member_mutate`).
#[derive(Clone, Debug, Serialize)]
pub struct AgentList {
    pub items: Vec<AgentView>,
    pub grantable_roles: Vec<&'static str>,
}

#[derive(Clone)]
pub struct AgentService {
    admin: AdminStore,
    store: AgentStore,
}

impl AgentService {
    pub fn new(admin: AdminStore, store: AgentStore) -> Self {
        Self { admin, store }
    }

    pub async fn list(
        &self,
        actor: UserAccountId,
        organization_id: OrganizationId,
    ) -> Result<AgentList, AgentError> {
        let scope = AdminScope::Organization(organization_id);
        let context = self
            .admin
            .authorization_context(actor, organization_id)
            .await
            .map_err(map_admin_error)?;
        if !context.allows(AdminPermission::MembersList, scope) {
            return Err(AgentError::Forbidden);
        }
        let grantable = if context.allows(AdminPermission::MemberMutate, scope) {
            grantable_roles(context.grant_ceiling(scope))
        } else {
            Vec::new()
        };
        Ok(AgentList {
            items: self.store.list(organization_id).await?,
            grantable_roles: grantable.into_iter().map(MembershipRole::as_str).collect(),
        })
    }

    pub async fn get(
        &self,
        actor: UserAccountId,
        organization_id: OrganizationId,
        agent_id: Uuid,
    ) -> Result<AgentView, AgentError> {
        let context = self
            .admin
            .authorization_context(actor, organization_id)
            .await
            .map_err(map_admin_error)?;
        if !context.allows(
            AdminPermission::MembersList,
            AdminScope::Organization(organization_id),
        ) {
            return Err(AgentError::Forbidden);
        }
        self.store
            .get(organization_id, agent_id)
            .await?
            .ok_or(AgentError::NotFound)
    }

    /// Creates an agent with an organization-wide membership in `role`.
    pub async fn create(
        &self,
        actor: UserAccountId,
        organization_id: OrganizationId,
        input: AgentInput,
        idempotency_key: AdminIdempotencyKey,
        request_id: Uuid,
    ) -> Result<MutationOutcome<AgentView>, AgentError> {
        if !valid_text(&input.name, 100) {
            return Err(AgentError::Invalid(
                "name must be 1 to 100 bytes without surrounding spaces or control characters",
            ));
        }
        if input
            .description
            .as_deref()
            .is_some_and(|description| !valid_text(description, 500))
        {
            return Err(AgentError::Invalid(
                "description must be 1 to 500 bytes without surrounding spaces or control characters",
            ));
        }
        let role = input.role.parse::<MembershipRole>().map_err(|_| {
            AgentError::Invalid("role must be owner, admin, member, auditor or read-only")
        })?;
        let target_id = deterministic_target_id(&[
            "agent.create",
            &organization_id.0.to_string(),
            &actor.0.to_string(),
            idempotency_key.as_str(),
        ]);
        let request = request(
            actor,
            organization_id,
            ROUTE_AGENTS,
            "POST",
            "agent.create",
            "agent.created",
            AuditTargetResource::Agent,
            target_id,
            idempotency_key,
            request_id,
            serde_json::json!({
                "name": input.name,
                "role": role.as_str(),
                "description": input.description,
            }),
        );
        match self
            .admin
            .coordinator()
            .begin(request)
            .await
            .map_err(map_admin_error)?
        {
            MutationStart::Replay(record) => Ok(MutationOutcome {
                item: replayed(record.response_metadata)?,
                replayed: true,
            }),
            MutationStart::New(mut mutation) => {
                let tx = mutation.transaction();
                let ceiling = InvitationStore::actor_ceiling(tx, organization_id, actor).await?;
                if !may_invite(ceiling, role) {
                    return Err(AgentError::EscalationDenied);
                }
                AgentStore::insert_agent(
                    tx,
                    organization_id,
                    target_id,
                    &input.name,
                    input.description.as_deref(),
                    role,
                    Some(actor),
                    crate::domain::audit::AuditActor::User(actor),
                )
                .await?;
                let view = AgentStore::view(tx, organization_id, target_id)
                    .await?
                    .ok_or(AgentError::NotFound)?;
                let next = mutation.next_version().get();
                mutation
                    .commit(
                        None,
                        Some(snapshot(true, next)),
                        Some(metadata(target_id, next, &view)?),
                    )
                    .await
                    .map_err(map_admin_error)?;
                Ok(MutationOutcome {
                    item: view,
                    replayed: false,
                })
            }
        }
    }

    /// Disables the agent and revokes its tokens; it can no longer sign in.
    /// Its audit trail keeps naming it.
    pub async fn disable(
        &self,
        actor: UserAccountId,
        organization_id: OrganizationId,
        agent_id: Uuid,
        idempotency_key: AdminIdempotencyKey,
        request_id: Uuid,
    ) -> Result<MutationOutcome<AgentView>, AgentError> {
        let request = request(
            actor,
            organization_id,
            ROUTE_AGENT,
            "DELETE",
            "agent.disable",
            "agent.disabled",
            AuditTargetResource::Agent,
            agent_id,
            idempotency_key,
            request_id,
            serde_json::json!({}),
        );
        match self
            .admin
            .coordinator()
            .begin(request)
            .await
            .map_err(map_admin_error)?
        {
            MutationStart::Replay(record) => Ok(MutationOutcome {
                item: replayed(record.response_metadata)?,
                replayed: true,
            }),
            MutationStart::New(mut mutation) => {
                let tx = mutation.transaction();
                let current = AgentStore::view(tx, organization_id, agent_id)
                    .await?
                    .ok_or(AgentError::NotFound)?;
                Self::check_ceiling(tx, organization_id, actor, agent_id, &current.role).await?;
                AgentStore::disable(tx, organization_id, agent_id).await?;
                let view = AgentStore::view(tx, organization_id, agent_id)
                    .await?
                    .ok_or(AgentError::NotFound)?;
                let next = mutation.next_version().get();
                mutation
                    .commit(
                        Some(snapshot(current.enabled, next.saturating_sub(1))),
                        Some(snapshot(false, next)),
                        Some(metadata(agent_id, next, &view)?),
                    )
                    .await
                    .map_err(map_admin_error)?;
                Ok(MutationOutcome {
                    item: view,
                    replayed: false,
                })
            }
        }
    }

    /// Creates a token for an enabled agent.
    pub async fn create_token(
        &self,
        actor: UserAccountId,
        organization_id: OrganizationId,
        agent_id: Uuid,
        input: AgentTokenInput,
        idempotency_key: AdminIdempotencyKey,
        request_id: Uuid,
    ) -> Result<MutationOutcome<CreatedAgentToken>, AgentError> {
        input.validate().map_err(AgentError::Invalid)?;
        let target_id = deterministic_target_id(&[
            "agent_token.create",
            &organization_id.0.to_string(),
            &agent_id.to_string(),
            &actor.0.to_string(),
            idempotency_key.as_str(),
        ]);
        let mut body = serde_json::json!({
            "agent_id": agent_id,
            "name": input.name,
            "expires_in_days": input.expires_in_days,
        });
        // Only when given, so a request from before tokens could be limited
        // keeps its fingerprint.
        if let Some(account) = input.service_account_id {
            body["service_account_id"] = serde_json::json!(account);
        }
        let request = request(
            actor,
            organization_id,
            ROUTE_AGENT_TOKENS,
            "POST",
            "agent_token.create",
            "agent_token.created",
            AuditTargetResource::AgentToken,
            target_id,
            idempotency_key,
            request_id,
            body,
        );
        match self
            .admin
            .coordinator()
            .begin(request)
            .await
            .map_err(map_admin_error)?
        {
            MutationStart::Replay(record) => Ok(MutationOutcome {
                item: CreatedAgentToken {
                    metadata: replayed(record.response_metadata)?,
                    token: None,
                    replay: true,
                },
                replayed: true,
            }),
            MutationStart::New(mut mutation) => {
                let tx = mutation.transaction();
                let Some(role) = AgentStore::enabled_role(tx, organization_id, agent_id).await?
                else {
                    return Err(
                        match AgentStore::view(tx, organization_id, agent_id).await? {
                            Some(_) => AgentError::AgentDisabled,
                            None => AgentError::NotFound,
                        },
                    );
                };
                Self::check_ceiling(tx, organization_id, actor, agent_id, role.as_str()).await?;
                let token = AgentStore::insert_token(
                    tx,
                    organization_id,
                    agent_id,
                    target_id,
                    &input,
                    Some(actor),
                )
                .await?;
                let view = AgentStore::token_view(tx, organization_id, target_id)
                    .await?
                    .ok_or(AgentError::NotFound)?;
                let next = mutation.next_version().get();
                let snapshot = AuditSnapshot {
                    enabled: Some(true),
                    expires_at: view.expires_at,
                    version: Some(next),
                    ..Default::default()
                };
                mutation
                    .commit(
                        None,
                        Some(snapshot),
                        Some(metadata(target_id, next, &view)?),
                    )
                    .await
                    .map_err(map_admin_error)?;
                Ok(MutationOutcome {
                    item: CreatedAgentToken {
                        metadata: view,
                        token: Some(token.as_str().to_owned()),
                        replay: false,
                    },
                    replayed: false,
                })
            }
        }
    }

    /// Revokes one of the agent's tokens; it stops working at once.
    #[allow(clippy::too_many_arguments)]
    pub async fn revoke_token(
        &self,
        actor: UserAccountId,
        organization_id: OrganizationId,
        agent_id: Uuid,
        token_id: Uuid,
        idempotency_key: AdminIdempotencyKey,
        request_id: Uuid,
    ) -> Result<MutationOutcome<crate::domain::agents::AgentTokenView>, AgentError> {
        let request = request(
            actor,
            organization_id,
            ROUTE_AGENT_TOKEN,
            "DELETE",
            "agent_token.revoke",
            "agent_token.revoked",
            AuditTargetResource::AgentToken,
            token_id,
            idempotency_key,
            request_id,
            serde_json::json!({ "agent_id": agent_id }),
        );
        match self
            .admin
            .coordinator()
            .begin(request)
            .await
            .map_err(map_admin_error)?
        {
            MutationStart::Replay(record) => Ok(MutationOutcome {
                item: replayed(record.response_metadata)?,
                replayed: true,
            }),
            MutationStart::New(mut mutation) => {
                let tx = mutation.transaction();
                let agent = AgentStore::view(tx, organization_id, agent_id)
                    .await?
                    .ok_or(AgentError::NotFound)?;
                if !agent.tokens.iter().any(|token| token.id == token_id) {
                    return Err(AgentError::NotFound);
                }
                Self::check_ceiling(tx, organization_id, actor, agent_id, &agent.role).await?;
                AgentStore::revoke_token(tx, organization_id, token_id).await?;
                let view = AgentStore::token_view(tx, organization_id, token_id)
                    .await?
                    .ok_or(AgentError::NotFound)?;
                let next = mutation.next_version().get();
                mutation
                    .commit(
                        Some(snapshot(true, next.saturating_sub(1))),
                        Some(snapshot(false, next)),
                        Some(metadata(token_id, next, &view)?),
                    )
                    .await
                    .map_err(map_admin_error)?;
                Ok(MutationOutcome {
                    item: view,
                    replayed: false,
                })
            }
        }
    }

    /// Refuses acting on an agent whose role is above the caller's own.
    /// Whether the actor ranks at or above everything the agent may do: its
    /// membership role and any role binding granted to it beyond that.
    async fn check_ceiling(
        tx: &mut sqlx::PgConnection,
        organization_id: OrganizationId,
        actor: UserAccountId,
        agent_id: Uuid,
        role: &str,
    ) -> Result<(), AgentError> {
        let role = role
            .parse::<MembershipRole>()
            .map_err(|_| AgentError::Store("agent membership role is invalid".into()))?;
        let agent = AgentStore::effective_role(tx, organization_id, agent_id, role).await?;
        let ceiling = InvitationStore::actor_ceiling(tx, organization_id, actor).await?;
        if ceiling.is_some_and(|ceiling| ceiling.can_grant(agent)) {
            Ok(())
        } else {
            Err(AgentError::EscalationDenied)
        }
    }
}

#[allow(clippy::too_many_arguments)]
fn request(
    actor: UserAccountId,
    organization_id: OrganizationId,
    route: &str,
    method: &str,
    operation: &str,
    action: &str,
    target: AuditTargetResource,
    target_id: Uuid,
    idempotency_key: AdminIdempotencyKey,
    request_id: Uuid,
    body: serde_json::Value,
) -> AdminMutationRequest {
    AdminMutationRequest {
        actor_id: actor,
        organization_id,
        scope: AdminScope::Organization(organization_id),
        permission: AdminPermission::MemberMutate,
        route: route.into(),
        method: method.into(),
        operation: AdminOperation::new(operation).expect("operation constant is valid"),
        idempotency_key,
        target_id,
        parent_id: None,
        target,
        audit_action: AuditAction::new(action).expect("audit action constant is valid"),
        if_match: IfMatch::Any,
        request_id,
        body,
    }
}

/// A version of 0 (a resource the operator's CLI made) is left out.
fn snapshot(enabled: bool, version: u64) -> AuditSnapshot {
    AuditSnapshot {
        enabled: Some(enabled),
        version: (version > 0).then_some(version),
        ..Default::default()
    }
}

fn metadata<T: Serialize>(
    resource_id: Uuid,
    version: u64,
    view: &T,
) -> Result<IdempotencyResultMetadata, AgentError> {
    Ok(IdempotencyResultMetadata {
        resource_id,
        version: Some(version),
        secret_unavailable_on_replay: false,
        snapshot: Some(
            serde_json::to_value(view)
                .map_err(|_| AgentError::Store("response snapshot is not serializable".into()))?,
        ),
    })
}

fn replayed<T: serde::de::DeserializeOwned>(
    metadata: Option<IdempotencyResultMetadata>,
) -> Result<T, AgentError> {
    let snapshot = metadata
        .and_then(|metadata| metadata.snapshot)
        .ok_or(AgentError::NotFound)?;
    serde_json::from_value(snapshot)
        .map_err(|_| AgentError::Store("recorded response snapshot is invalid".into()))
}

fn map_admin_error(error: AdminStoreError) -> AgentError {
    match error {
        AdminStoreError::Authorization(_) => AgentError::Forbidden,
        AdminStoreError::ResourceNotFound => AgentError::NotFound,
        AdminStoreError::IdempotencyConflict => AgentError::IdempotencyConflict,
        AdminStoreError::IdempotencyInProgress => AgentError::IdempotencyInProgress,
        other => AgentError::Admin(other),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn openapi_contract_documents_every_route() {
        let contract: serde_json::Value =
            serde_json::from_str(include_str!("../../openapi/admin-agents-v1.json")).unwrap();
        let mut documented: Vec<&str> = contract["paths"]
            .as_object()
            .unwrap()
            .keys()
            .map(String::as_str)
            .collect();
        documented.sort_unstable();
        let mut routes = vec![
            ROUTE_AGENTS,
            ROUTE_AGENT,
            ROUTE_AGENT_TOKENS,
            ROUTE_AGENT_TOKEN,
        ];
        routes.sort_unstable();
        assert_eq!(documented, routes);
    }
}
